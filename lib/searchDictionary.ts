// Helper function to find services by search term
export function findServicesByTerm(searchTerm: string): { serviceNames: string[], categories: string[] } {
  const lowerTerm = searchTerm.toLowerCase().trim()
  const matchingTerms = searchDictionary.filter(mapping => 
    mapping.term.toLowerCase() === lowerTerm || 
    mapping.term.toLowerCase().includes(lowerTerm) ||
    lowerTerm.includes(mapping.term.toLowerCase())
  )
  
  const serviceNames = new Set<string>()
  const categories = new Set<string>()
  
  matchingTerms.forEach(mapping => {
    mapping.serviceNames.forEach(name => serviceNames.add(name))
    mapping.categories?.forEach(cat => categories.add(cat))
  })
  
  return {
    serviceNames: Array.from(serviceNames),
    categories: Array.from(categories)
  }
}

